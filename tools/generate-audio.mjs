// Generates natural-voice MP3 files for the spoken explanations in audio.js
// with the ElevenLabs API. Same logic as generate-audio.ps1, for running on
// GitHub Actions (or any computer with Node 18+).
//
//   ELEVENLABS_API_KEY=... node tools/generate-audio.mjs [keys...]
//   node tools/generate-audio.mjs --dry-run      -> only list what would be generated
//
// Only explanations whose text, voice or model changed are generated again.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const tools = path.dirname(fileURLToPath(import.meta.url));
const site = path.dirname(tools);
const audioJs = path.join(site, 'audio.js');
const outDir = path.join(site, 'audio');
const manJson = path.join(outDir, 'manifest.json');
const manJs = path.join(site, 'audio-files.js');
const settingsFile = path.join(tools, 'elevenlabs-settings.json');

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const only = args.filter(a => !a.startsWith('--'));

// Must match fnv() in index.html (FNV-1a 32-bit over UTF-16 code units).
function fnv1a(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}

// ---- read explanations ----
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(audioJs, 'utf8'), sandbox);
const data = sandbox.window.AUDIO || {};
let keys = Object.keys(data).sort();
if (only.length) keys = keys.filter(k => only.includes(k));

const cfg = JSON.parse(fs.readFileSync(settingsFile, 'utf8'));
const endpoint = cfg.endpoint || (String(cfg.model_id).startsWith('eleven_v4') ? 'dialogue' : 'tts');

// ---- manifest ----
let man = {};
if (fs.existsSync(manJson)) man = JSON.parse(fs.readFileSync(manJson, 'utf8').replace(/^﻿/, ''));
function saveManifest() {
  fs.mkdirSync(outDir, { recursive: true });
  const ordered = {};
  for (const k of Object.keys(man).sort()) ordered[k] = man[k];
  const json = JSON.stringify(ordered, null, 4);
  fs.writeFileSync(manJson, json + '\n');
  fs.writeFileSync(manJs, `// Generated by tools/generate-audio - do not edit by hand.\nwindow.AUDIO_FILES = ${json};\n`);
}

// ---- what needs generating ----
const todo = []; let chars = 0;
for (const k of keys) {
  const paras = data[k].map(String);
  const text = paras.join('\n\n');
  const hash = fnv1a(text);
  const file = path.join(outDir, `${k}.mp3`);
  const cur = man[k];
  if (cur && cur.hash === hash && cur.voice === cfg.voice_id && cur.model === cfg.model_id && fs.existsSync(file)) continue;
  todo.push({ key: k, paras, hash, file });
  chars += text.length;
}

// remove entries whose explanation was deleted from audio.js (only on a full run)
function prune() {
  if (only.length) return;
  for (const k of Object.keys(man)) {
    if (!(k in data)) { delete man[k]; const f = path.join(outDir, `${k}.mp3`); if (fs.existsSync(f)) fs.unlinkSync(f); }
  }
}

console.log(`To generate: ${todo.length} explanation(s), about ${chars.toLocaleString()} characters of ElevenLabs credit.`);
console.log(`Voice: ${cfg.voice_id}   Model: ${cfg.model_id}   API: ${endpoint}`);
if (todo.length) console.log('Keys: ' + todo.map(t => t.key).join(' '));
if (dryRun) process.exit(0);
if (!todo.length) { prune(); saveManifest(); console.log('Everything is up to date.'); process.exit(0); }

const key = process.env.ELEVENLABS_API_KEY;
if (!key) { console.error('ELEVENLABS_API_KEY is not set.'); process.exit(1); }

function splitChunks(paras, max) {
  // Group whole paragraphs into chunks of at most max characters (long paragraphs split on sentences).
  const out = []; let cur = '';
  for (const p of paras) {
    const pieces = p.length > max ? p.split(/(?<=[.!?])\s+/) : [p];
    for (const s of pieces) {
      if (cur.length > 0 && cur.length + s.length + 2 > max) { out.push(cur); cur = ''; }
      if (cur.length > 0) cur += '\n\n';
      cur += s;
    }
  }
  if (cur.length > 0) out.push(cur);
  return out;
}

async function tts(text, prev) {
  let url, body;
  if (endpoint === 'dialogue') {
    url = `https://api.elevenlabs.io/v1/text-to-dialogue?output_format=${cfg.output_format}`;
    body = { inputs: [{ text, voice_id: cfg.voice_id }], model_id: cfg.model_id, language_code: 'he' };
    if (prev) body.previous_text = prev;
  } else {
    url = `https://api.elevenlabs.io/v1/text-to-speech/${cfg.voice_id}?output_format=${cfg.output_format}`;
    const vs = { stability: Number(cfg.stability), similarity_boost: Number(cfg.similarity_boost) };
    if (cfg.style != null) vs.style = Number(cfg.style);
    if (cfg.speed != null) vs.speed = Number(cfg.speed);
    if (cfg.use_speaker_boost != null) vs.use_speaker_boost = Boolean(cfg.use_speaker_boost);
    body = { text, model_id: cfg.model_id, voice_settings: vs };
  }
  for (let attempt = 1; ; attempt++) {
    const r = await fetch(url, { method: 'POST', headers: { 'xi-api-key': key, 'Content-Type': 'application/json', Accept: 'audio/mpeg' }, body: JSON.stringify(body) });
    if (r.ok) return Buffer.from(await r.arrayBuffer());
    const msg = (await r.text()).slice(0, 400);
    if ((r.status === 429 || r.status >= 500) && attempt < 4) { await new Promise(res => setTimeout(res, 5000 * attempt)); continue; }
    throw new Error(`ElevenLabs request failed: HTTP ${r.status} - ${msg}`);
  }
}

fs.mkdirSync(outDir, { recursive: true });
let max = endpoint === 'dialogue' ? 1900 : 4500;
if (cfg.max_chars) max = Number(cfg.max_chars);
let i = 0;
for (const t of todo) {
  i++;
  process.stdout.write(`[${i}/${todo.length}] ${t.key} ...`);
  const parts = [];
  try {
    let prev = '';
    for (const c of splitChunks(t.paras, max)) {
      parts.push(await tts(c, prev));
      prev = c.length > 100 ? c.slice(-100) : c;
    }
  } catch (e) {
    console.log(' failed.');
    console.error(e.message);
    saveManifest();
    console.log('Stopped. Files generated so far were kept; run again to continue.');
    process.exit(1);
  }
  const buf = Buffer.concat(parts);
  fs.writeFileSync(t.file, buf);
  man[t.key] = { hash: t.hash, voice: cfg.voice_id, model: cfg.model_id, file: `audio/${t.key}.mp3?v=${t.hash}` };
  saveManifest();
  console.log(` done (${Math.round(buf.length / 1024).toLocaleString()} KB)`);
}
prune();
saveManifest();
console.log('Finished.');
