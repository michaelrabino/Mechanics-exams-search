# Generates natural-voice MP3 files for the spoken explanations in audio.js,
# using the ElevenLabs text-to-speech API.
#
# Usage (from the tools folder):  double-click generate-audio.bat
#   or:  powershell -ExecutionPolicy Bypass -File generate-audio.ps1 [keys...]
#   e.g. generate-audio.bat 2024b-94-3      -> only that question
#
# The API key is never saved to disk. It is read from the ELEVENLABS_API_KEY
# environment variable, or typed in (hidden) when the script starts.
# Only explanations whose text, voice or model changed are generated again.

param([string[]]$Only)

$ErrorActionPreference = 'Stop'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$utf8 = New-Object System.Text.UTF8Encoding($false)

$tools    = Split-Path -Parent $MyInvocation.MyCommand.Path
$site     = Split-Path -Parent $tools
$audioJs  = Join-Path $site 'audio.js'
$outDir   = Join-Path $site 'audio'
$manJson  = Join-Path $outDir 'manifest.json'
$manJs    = Join-Path $site 'audio-files.js'
$settings = Join-Path $tools 'elevenlabs-settings.json'

function Fnv1a([string]$s) {
  # Must match fnv() in index.html (FNV-1a 32-bit over UTF-16 code units).
  [uint64]$h = 2166136261
  foreach ($ch in $s.ToCharArray()) {
    $h = $h -bxor [uint64][int]$ch
    $h = ($h * 16777619) % 4294967296
  }
  return ('{0:x8}' -f $h)
}

# ---- read explanations -------------------------------------------------------
if (-not (Test-Path $audioJs)) { throw "audio.js not found next to the tools folder: $audioJs" }
$raw = [IO.File]::ReadAllText($audioJs, [Text.Encoding]::UTF8)
$start = $raw.IndexOf('{'); $end = $raw.LastIndexOf('}')
if ($start -lt 0 -or $end -le $start) { throw 'Could not read audio.js (no { ... } block found).' }
$data = $raw.Substring($start, $end - $start + 1) | ConvertFrom-Json
$keys = @($data.PSObject.Properties.Name | Sort-Object)
if ($Only) { $keys = @($keys | Where-Object { $Only -contains $_ }) }
if ($keys.Count -eq 0) { Write-Host 'No matching explanations found in audio.js.'; exit 1 }

# ---- settings (voice / model) ------------------------------------------------
$cfg = $null
if (Test-Path $settings) { $cfg = [IO.File]::ReadAllText($settings, [Text.Encoding]::UTF8) | ConvertFrom-Json }
if (-not $cfg -or -not $cfg.voice_id) {
  Write-Host ''
  Write-Host 'First run: choose a voice in ElevenLabs (Voices -> pick a Hebrew voice -> "Copy voice ID").'
  $vid = (Read-Host 'Paste the voice ID').Trim()
  if (-not $vid) { throw 'A voice ID is required.' }
  $cfg = [pscustomobject]@{ voice_id = $vid; model_id = 'eleven_v3'; output_format = 'mp3_44100_64'; stability = 0.5; similarity_boost = 0.75 }
  [IO.File]::WriteAllText($settings, ($cfg | ConvertTo-Json), $utf8)
  Write-Host "Saved voice settings to $settings (you can edit it later)."
}

# Eleven v4 is served by the Text to Dialogue API; older models by Text to Speech.
$endpoint = $cfg.endpoint
if (-not $endpoint) { if ([string]$cfg.model_id -like 'eleven_v4*') { $endpoint = 'dialogue' } else { $endpoint = 'tts' } }

# ---- manifest ----------------------------------------------------------------
$man = @{}
if (Test-Path $manJson) {
  $m = [IO.File]::ReadAllText($manJson, [Text.Encoding]::UTF8) | ConvertFrom-Json
  foreach ($p in $m.PSObject.Properties) { $man[$p.Name] = $p.Value }
}
function Save-Manifest {
  if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
  $ordered = [ordered]@{}
  foreach ($k in ($man.Keys | Sort-Object)) { $ordered[$k] = $man[$k] }
  $json = ($ordered | ConvertTo-Json -Depth 4)
  if ($ordered.Count -eq 0) { $json = '{}' }
  [IO.File]::WriteAllText($manJson, $json, $utf8)
  [IO.File]::WriteAllText($manJs, "// Generated by tools/generate-audio.ps1 - do not edit by hand.`nwindow.AUDIO_FILES = $json;`n", $utf8)
}

# ---- what needs generating ---------------------------------------------------
$todo = @(); $chars = 0
foreach ($k in $keys) {
  $paras = @($data.$k | ForEach-Object { [string]$_ })
  $text  = $paras -join "`n`n"
  $hash  = Fnv1a $text
  $file  = Join-Path $outDir "$k.mp3"
  $cur   = $man[$k]
  if ($cur -and $cur.hash -eq $hash -and $cur.voice -eq $cfg.voice_id -and $cur.model -eq $cfg.model_id -and (Test-Path $file)) { continue }
  $todo += [pscustomobject]@{ key = $k; paras = $paras; hash = $hash; file = $file }
  $chars += $text.Length
}
if ($todo.Count -eq 0) { Save-Manifest; Write-Host 'Everything is up to date. Nothing to generate.'; exit 0 }

Write-Host ''
Write-Host ("To generate: {0} explanation(s), about {1:N0} characters of ElevenLabs credit." -f $todo.Count, $chars)
Write-Host ("Voice: {0}   Model: {1}   API: {2}" -f $cfg.voice_id, $cfg.model_id, $endpoint)
$ok = Read-Host 'Continue? (y/n)'
if ($ok -notmatch '^[yY]') { Write-Host 'Cancelled.'; exit 0 }

# ---- API key (never stored) --------------------------------------------------
$key = $env:ELEVENLABS_API_KEY
if (-not $key) {
  $sec = Read-Host 'ElevenLabs API key (input hidden)' -AsSecureString
  $key = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec))
}
if (-not $key) { throw 'An API key is required.' }

function Split-Chunks($paras, [int]$max) {
  # Group whole paragraphs into chunks of at most $max characters (long paragraphs split on sentences).
  $out = New-Object System.Collections.Generic.List[string]; $cur = ''
  foreach ($p in $paras) {
    $pieces = @($p)
    if ($p.Length -gt $max) { $pieces = [regex]::Split($p, '(?<=[.!?])\s+') }
    foreach ($s in $pieces) {
      if ($cur.Length -gt 0 -and ($cur.Length + $s.Length + 2) -gt $max) { $out.Add($cur); $cur = '' }
      if ($cur.Length -gt 0) { $cur += "`n`n" }
      $cur += $s
    }
  }
  if ($cur.Length -gt 0) { $out.Add($cur) }
  return ,$out
}

# Corporate networks: go through the system proxy with the Windows login (like the browser does).
$script:proxy = [Net.WebRequest]::GetSystemWebProxy()
$script:proxy.Credentials = [Net.CredentialCache]::DefaultNetworkCredentials
$script:askedProxy = $false

function Invoke-Tts([string]$text, [string]$prev) {
  for ($attempt = 1; $attempt -le 2; $attempt++) {
    try { return (Send-Tts $text $prev) }
    catch [System.Net.WebException] {
      $resp = $_.Exception.Response
      if ($resp -and [int]$resp.StatusCode -eq 407 -and -not $script:askedProxy) {
        $script:askedProxy = $true
        Write-Host ''
        Write-Host 'The network proxy asks for a user name and password (the same ones you use to log in to this computer / the organization network).' -ForegroundColor Yellow
        $c = Get-Credential -Message 'Network proxy login'
        if (-not $c) { throw 'Proxy login cancelled.' }
        $script:proxy.Credentials = $c.GetNetworkCredential()
        continue
      }
      $msg = $_.Exception.Message
      if ($resp) {
        $code = [int]$resp.StatusCode
        $reader = New-Object IO.StreamReader($resp.GetResponseStream())
        $body = $reader.ReadToEnd()
        if ($code -eq 407) { $body = 'the network proxy refused the login. Try another network (e.g. home), or ask IT to allow api.elevenlabs.io.' }
        elseif ($body.Length -gt 400) { $body = $body.Substring(0, 400) + '...' }
        $msg = "HTTP $code - " + $body
      }
      throw "ElevenLabs request failed: $msg"
    }
  }
}

function Send-Tts([string]$text, [string]$prev) {
  if ($endpoint -eq 'dialogue') {
    $url = "https://api.elevenlabs.io/v1/text-to-dialogue?output_format=$($cfg.output_format)"
    $req = @{ inputs = @(@{ text = $text; voice_id = $cfg.voice_id }); model_id = $cfg.model_id; language_code = 'he' }
    if ($prev) { $req.previous_text = $prev }
    $body = $req | ConvertTo-Json -Depth 5
  } else {
  $url  = "https://api.elevenlabs.io/v1/text-to-speech/$($cfg.voice_id)?output_format=$($cfg.output_format)"
  $vs = @{ stability = [double]$cfg.stability; similarity_boost = [double]$cfg.similarity_boost }
  if ($null -ne $cfg.style) { $vs.style = [double]$cfg.style }
  if ($null -ne $cfg.speed) { $vs.speed = [double]$cfg.speed }
  if ($null -ne $cfg.use_speaker_boost) { $vs.use_speaker_boost = [bool]$cfg.use_speaker_boost }
  $body = @{ text = $text; model_id = $cfg.model_id; voice_settings = $vs } | ConvertTo-Json -Depth 4
  }
  $wc = New-Object System.Net.WebClient
  $wc.Proxy = $script:proxy
  $wc.Headers.Add('xi-api-key', $key)
  $wc.Headers.Add('Content-Type', 'application/json')
  $wc.Headers.Add('Accept', 'audio/mpeg')
  try { return $wc.UploadData($url, 'POST', $utf8.GetBytes($body)) }
  finally { $wc.Dispose() }
}

if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
$i = 0
foreach ($t in $todo) {
  $i++
  Write-Host ("[{0}/{1}] {2} ..." -f $i, $todo.Count, $t.key) -NoNewline
  $max = 4500; if ($endpoint -eq 'dialogue') { $max = 1900 }; if ($cfg.max_chars) { $max = [int]$cfg.max_chars }
  $chunks = Split-Chunks $t.paras $max
  $ms = New-Object IO.MemoryStream
  try {
    $prev = ''
    foreach ($c in $chunks) {
      $b = Invoke-Tts $c $prev; $ms.Write($b, 0, $b.Length)
      $prev = $c; if ($prev.Length -gt 100) { $prev = $prev.Substring($prev.Length - 100) }
    }
  } catch {
    Write-Host ' failed.'
    Write-Host $_.Exception.Message -ForegroundColor Red
    Save-Manifest
    Write-Host 'Stopped. Files generated so far were kept; run the script again to continue.'
    exit 1
  }
  [IO.File]::WriteAllBytes($t.file, $ms.ToArray())
  $man[$t.key] = [pscustomobject]@{ hash = $t.hash; voice = $cfg.voice_id; model = $cfg.model_id; file = "audio/$($t.key).mp3?v=$($t.hash)" }
  Save-Manifest
  Write-Host (" done ({0:N0} KB)" -f ($ms.Length / 1KB))
}

# remove entries whose explanation was deleted from audio.js (only on a full run)
if (-not $Only) {
  foreach ($k in @($man.Keys)) {
    if (-not ($data.PSObject.Properties.Name -contains $k)) {
      $man.Remove($k)
      $f = Join-Path $outDir "$k.mp3"; if (Test-Path $f) { Remove-Item $f }
    }
  }
  Save-Manifest
}
Write-Host ''
Write-Host 'Finished. Open index.html (Edge or Chrome) and press play on the explanation.'
